#!/usr/bin/env -S npx tsx
/**
 * Writes the record of processing published with each release: for every customer field, where it
 * may go and why (from privacy/datamap.yml), and where the latest production drill actually saw it.
 * Usage: tsx packages/drill/src/ropa.ts <datamap.yml> <out.md> [production leak-report.json]
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { parse } from "yaml";
import { FIELDS } from "./canary";
import { parseDataMap } from "./datamap";
import type { DrillReport } from "./types";

const [mapPath, outPath, reportPath] = process.argv.slice(2);
if (!mapPath || !outPath) {
  console.error("usage: ropa.ts <datamap.yml> <out.md> [leak-report.json]");
  process.exit(2);
}
const source = readFileSync(mapPath, "utf8");
const map = parseDataMap(source);
const raw = parse(source) as { destinations: Record<string, { purpose?: string; recipient?: string; retention?: string }> };
const report: DrillReport | null = reportPath && existsSync(reportPath) ? JSON.parse(readFileSync(reportPath, "utf8")) : null;

const label = (id: string) => map.destinations.find((d) => d.id === id)?.label ?? id;
const seen = (field: string, dest: string) => report?.hits.some((h) => h.field === field && h.destination === dest) ?? false;

const lines: string[] = [
  "# Record of processing: Greenstem customer data",
  "",
  `Generated by Leak Gate for release ${process.env.CI_COMMIT_SHORT_SHA ?? "local"} on ${new Date().toISOString().slice(0, 10)}.`,
  "Allowed flows come from `privacy/datamap.yml`. Observed flows come from a drill of this release in production" +
    (report ? ` (run \`${report.runId}\`, ${report.status === "passed" ? "no leaks" : `${report.leaks} leaks`}).` : " (no drill report attached)."),
  "",
  "## Recipients",
  "",
  "| Destination | Recipient | Purpose | Retention |",
  "|---|---|---|---|",
  ...map.destinations.map((d) => {
    const r = raw.destinations[d.id] ?? {};
    return `| ${d.label} | ${r.recipient ?? ""} | ${r.purpose ?? ""} | ${r.retention ?? ""} |`;
  }),
  "",
  "## Customer fields",
  "",
  "| Field | May go to | Observed in production |",
  "|---|---|---|",
  ...FIELDS.map((f) => {
    const allowed = map.allowed[f].map(label).join(", ") || "nowhere in clear text";
    const observed = report
      ? map.destinations.filter((d) => seen(f, d.id)).map((d) => `${d.label}${map.allowed[f].includes(d.id) ? "" : " (not allowed)"}`).join(", ") || "nowhere"
      : "not drilled";
    return `| ${f} | ${allowed} | ${observed} |`;
  }),
  "",
  "Passwords are stored only as salted scrypt hashes. Every value in the drill is synthetic.",
  "",
];
writeFileSync(outPath, lines.join("\n"));
console.log(`wrote ${outPath}`);
